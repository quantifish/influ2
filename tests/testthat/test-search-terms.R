search_term_model <- function(f, backend = "glm") {
  if (backend == "brmsfit") return(structure(list(formula = list(formula = f)), class = backend))
  if (backend == "tinyVAST") return(structure(list(formula = f, internal = list()), class = backend))
  structure(list(terms = stats::terms(f)), class = backend)
}

search_term_ids <- function(spec, terms) spec$terms$id[match(vapply(terms, .search_term_key, character(1)), spec$terms$term)]

test_that("model-search specifications keep annual, offset, and random blocks intact", {
  model <- search_term_model(y ~ factor(year) + poly(depth, 3) + soak + (1 | vessel) + offset(log(effort)))
  spec <- .search_prepare_spec(model, year = "year")
  expect_identical(spec$backend, "glm")
  expect_equal(spec$terms$protected, c(TRUE, FALSE, FALSE, TRUE, TRUE))
  expect_equal(spec$terms$type, c("fixed", "fixed", "fixed", "random", "offset"))
  expect_length(spec$optional_ids, 2L)
  expect_true(.search_legal(spec, spec$protected_ids))
  expect_true(.search_legal(spec, spec$terms$id))
  expect_false(.search_legal(spec, spec$optional_ids))
  reduced <- .search_formula(spec, spec$protected_ids)
  expect_setequal(.search_formula_terms(reduced), c("factor(year)", "1 | vessel", "offset(log(effort))"))
  expect_identical(reduced[[2L]], quote(y))
  expect_identical(environment(reduced), environment(stats::formula(model)))
  expect_identical(spec$original_ids, spec$terms$id)
  expect_false(any(vapply(spec, is.function, logical(1))))
})

test_that("upper/lower scope and include cannot silently change response or offsets", {
  model <- search_term_model(y ~ year + x + z + (1 | vessel) + offset(log(effort)))
  spec <- .search_prepare_spec(model, "year", scope = list(lower = ~ year + x, upper = ~ year + x + z))
  expect_setequal(spec$terms$term[spec$terms$protected], c("year", "x", "1 | vessel", "offset(log(effort))"))
  expect_length(spec$optional_ids, 1L)
  expect_setequal(.search_formula_terms(spec$upper_formula), .search_formula_terms(stats::formula(model)))
  expect_error(.search_prepare_spec(model, "year", scope = other ~ year + x), "original response")
  expect_error(.search_prepare_spec(model, "year", scope = ~ year + x + offset(2 * log(effort))), "original offset")
  expect_error(.search_prepare_spec(model, "year", scope = ~ 0 + year + x), "intercept")
  expect_error(.search_prepare_spec(model, "year", include = ~unknown), "Unknown included")
  expect_error(.search_prepare_spec(model, "year", scope = list(lower = ~year + unknown)), "lower scope")
  expect_error(.search_prepare_spec(model, "year", scope = list(bad = ~year)), "named list")
  expect_error(.search_prepare_spec(model, "year", scope = "~ year"), "named list")
  spec <- .search_prepare_spec(model, "year", include = ~x)
  expect_true(spec$terms$protected[spec$terms$term == "x"])
  expect_error(.search_prepare_spec(model, "year", include = ~x, optional = "x"), "cannot be optional")
  expect_error(.search_prepare_spec(model, "year", optional = "year"), "cannot be optional")
  expect_error(.search_prepare_spec(model, "year", optional = "offset(log(effort))"), "cannot be optional")
})

test_that("explicit optional terms release only nominated structural blocks", {
  model <- search_term_model(y ~ year + x + z + (1 | vessel))
  spec <- .search_prepare_spec(model, "year", optional = "(1 | vessel)")
  expect_setequal(spec$terms$term[!spec$terms$protected], "1 | vessel")
  expect_true(.search_legal(spec, spec$protected_ids))
  expect_false("1 | vessel" %in% .search_formula_terms(.search_formula(spec, spec$protected_ids)))
  spec <- .search_prepare_spec(model, "year", optional = c("x", "z"))
  expect_setequal(spec$terms$term[!spec$terms$protected], c("x", "z"))
  expect_true(spec$terms$protected[spec$terms$type == "random"])
  expect_error(.search_prepare_spec(model, "year", optional = "unknown"), "Unknown optional")
  expect_error(.search_prepare_spec(model, "year", optional = c("x", "x")), "distinct")
  expect_error(.search_prepare_spec(model, "year", optional = c("(1 | vessel)", "1 | vessel")), "equivalent")
  expect_error(.search_prepare_spec(model, "year", optional = character()), "distinct")
  formula_spec <- .search_prepare_spec(model, "year", optional = ~x + z)
  expect_identical(formula_spec$optional_ids, .search_prepare_spec(model, "year", optional = c("x", "z"))$optional_ids)
  random_spec <- .search_prepare_spec(model, "year", optional = ~(1 | vessel))
  expect_setequal(random_spec$terms$term[!random_spec$terms$protected], "1 | vessel")
  expect_error(.search_prepare_spec(model, "year", optional = y ~ x), "one-sided")
  expect_error(.search_prepare_spec(model, "year", optional = ~year), "cannot be optional")
  expect_error(.search_prepare_spec(model, "year", optional = ~unknown), "Unknown optional")
})

test_that("smooths and polynomial/factor bases are whole atomic blocks", {
  model <- search_term_model(y ~ year + s(depth, k = 6) + te(X, Y) + s(vessel, bs = "re") + poly(soak, 3))
  spec <- .search_prepare_spec(model, "year")
  expect_equal(spec$terms$type, c("fixed", "smooth", "multivariable_smooth", "random", "fixed"))
  expect_setequal(spec$terms$term[!spec$terms$protected], c("s(depth, k = 6)", "poly(soak, 3)"))
  expect_length(spec$terms$id, 5L)
  spec <- .search_prepare_spec(model, "year", optional = "te(X, Y)")
  expect_setequal(spec$terms$term[!spec$terms$protected], "te(X, Y)")
  expect_length(spec$optional_ids, 1L)
  expect_true(.search_legal(spec, spec$protected_ids))
  structured <- search_term_model(y ~ year + ar1(month + 0 | vessel))
  expect_equal(.search_prepare_spec(structured, "year")$terms$type, c("fixed", "random"))
})

test_that("by-smooth and tensor-interaction dependencies preserve existing parents", {
  model <- search_term_model(y ~ year + season + s(depth, by = season))
  spec <- .search_prepare_spec(model, "year", optional = c("season", "s(depth, by = season)"))
  smooth <- search_term_ids(spec, "s(depth, by = season)")
  season <- search_term_ids(spec, "season")
  expect_identical(spec$dependencies[[smooth]], season)
  expect_false(.search_legal(spec, c(spec$protected_ids, smooth)))
  expect_true(.search_legal(spec, c(spec$protected_ids, smooth, season)))
  model <- search_term_model(y ~ year + s(X) + s(Y) + ti(X, Y))
  spec <- .search_prepare_spec(model, "year", optional = c("s(X)", "s(Y)", "ti(X, Y)"))
  tensor <- search_term_ids(spec, "ti(X, Y)")
  parents <- search_term_ids(spec, c("s(X)", "s(Y)"))
  expect_setequal(spec$dependencies[[tensor]], parents)
  expect_false(.search_legal(spec, c(spec$protected_ids, tensor)))
  expect_true(.search_legal(spec, c(spec$protected_ids, tensor, parents)))
})

test_that("interaction hierarchy preserves present parents without inventing absent ones", {
  model <- search_term_model(y ~ year + x * z * w)
  spec <- .search_prepare_spec(model, "year")
  xyz <- search_term_ids(spec, "x:z:w")
  parents <- search_term_ids(spec, c("x", "z", "w", "x:z", "x:w", "z:w"))
  expect_setequal(spec$dependencies[[xyz]], parents)
  expect_false(.search_legal(spec, c(spec$protected_ids, xyz)))
  expect_true(.search_legal(spec, c(spec$protected_ids, parents, xyz)))
  expect_error(.search_formula(spec, c(spec$protected_ids, xyz)), "Illegal")
  spec <- .search_prepare_spec(model, "year", include = ~x:z)
  expect_true(all(search_term_ids(spec, c("x", "z", "x:z")) %in% spec$protected_ids))

  model <- search_term_model(y ~ fyear:season + fyear:region + depth)
  spec <- .search_prepare_spec(model, "fyear", include = ~fyear:season)
  expect_setequal(spec$terms$term[spec$terms$protected], "fyear:season")
  expect_true("fyear:region" %in% spec$terms$term[!spec$terms$protected])
  expect_false(any(c("fyear", "season") %in% spec$terms$term))
  expect_setequal(.search_formula_terms(.search_formula(spec, spec$protected_ids)), "fyear:season")
  auto <- .search_prepare_spec(model, "fyear")
  expect_setequal(auto$terms$term[auto$terms$protected], c("fyear:season", "fyear:region"))
})

test_that("grouped blocks are all-or-none and inherit protected dependencies", {
  model <- search_term_model(y ~ year + x + z + x:z + w)
  spec <- .search_prepare_spec(model, "year", blocks = list(Shape = c("x", "z")))
  ids <- search_term_ids(spec, c("x", "z"))
  expect_false(.search_legal(spec, c(spec$protected_ids, ids[1L])))
  expect_true(.search_legal(spec, c(spec$protected_ids, ids)))
  spec <- .search_prepare_spec(model, "year", include = ~w,
    blocks = list(Linked = c("w", "x:z")))
  expect_setequal(spec$terms$term[spec$terms$protected], c("year", "w", "x:z", "x", "z"))
  expect_true(.search_legal(spec, spec$protected_ids))
  expect_error(.search_prepare_spec(model, "year", blocks = list(A = "x", B = "x")), "multiple")
  expect_error(.search_prepare_spec(model, "year", blocks = list(A = "unknown")), "unknown")
  expect_error(.search_prepare_spec(model, "year", blocks = list("x")), "uniquely named")
})

test_that("joint sdmTMB searches change only one named component", {
  occurrence <- y ~ year + x + offset(log(effort))
  positive <- y ~ year + z + (1 | vessel)
  model <- structure(list(formula = list(occurrence, positive),
    family = list(delta = TRUE), time = "year"), class = "sdmTMB")
  expect_error(.search_prepare_spec(model), "Select.*component")
  spec <- .search_prepare_spec(model, component = "occurrence")
  expect_identical(spec$component_index, 1L)
  reduced <- .search_formula(spec, spec$protected_ids)
  expect_identical(reduced[[2L]], positive)
  expect_setequal(.search_formula_terms(reduced[[1L]]), c("year", "offset(log(effort))"))
  spec <- .search_prepare_spec(model, component = "positive")
  expect_identical(spec$component_index, 2L)
  reduced <- .search_formula(spec, spec$protected_ids)
  expect_identical(reduced[[1L]], occurrence)
  expect_setequal(.search_formula_terms(reduced[[2L]]), c("year", "1 | vessel"))
  expect_identical(.search_prepare_spec(model, component = "encounter")$component, "occurrence")
  expect_error(.search_prepare_spec(model, component = "combined"), "one component")
})

test_that("brms and tinyVAST main formulas are supported without altering auxiliary objects", {
  f <- y ~ year + x + (1 | vessel)
  environment(f) <- baseenv()
  model <- search_term_model(f, "brmsfit")
  model$formula$pforms <- list(sigma = stats::as.formula("~x", env = baseenv()))
  saved <- serialize(model, NULL)
  spec <- .search_prepare_spec(model, "year")
  expect_identical(spec$backend, "brmsfit")
  expect_setequal(.search_formula_terms(.search_formula(spec, spec$protected_ids)), c("year", "1 | vessel"))
  expect_identical(serialize(model, NULL), saved)
  model <- search_term_model(f, "tinyVAST")
  spec <- .search_prepare_spec(model, "year")
  expect_identical(spec$backend, "tinyVAST")
  expect_error(.search_prepare_spec(model, "year", component = "dispersion"), "main mean")
})

test_that("search year, empty candidate IDs, and no-intercept formulas are validated", {
  model <- search_term_model(y ~ 0 + year + x)
  spec <- .search_prepare_spec(model, "year")
  f <- .search_formula(spec, spec$protected_ids)
  expect_identical(attr(stats::terms(f), "intercept"), 0L)
  expect_identical(spec$year, "year")
  expect_identical(.search_prepare_spec(model)$year, "year")
  expect_error(.search_prepare_spec(model, "missing"), "annual predictor")
  expect_error(.search_prepare_spec(model, character()), "name one")
  expect_error(.search_prepare_spec(model, NA_character_), "name one")
  expect_false(.search_legal(spec, "unknown"))
  expect_false(.search_legal(spec, NA_character_))
  expect_false(.search_legal(spec, c(spec$protected_ids, spec$protected_ids)))
  expect_false(.search_legal(spec, NULL))
  expect_error(.search_term_key("x +"), "Invalid")
  empty <- .search_formula_from_terms(stats::formula(model), character())
  expect_identical(attr(stats::terms(empty), "intercept"), 0L)
})

test_that("native temporal processes allow spatial annual searches without invented year terms", {
  model <- structure(list(formula = y ~ depth, family = list(delta = FALSE),
    time = "year", spatiotemporal = "iid"), class = "sdmTMB")
  spec <- .search_prepare_spec(model, "year")
  expect_identical(spec$terms$term, "depth")
  expect_length(spec$protected_ids, 0L)
  expect_true(.search_legal(spec, character()))
  expect_identical(.search_formula_terms(.search_formula(spec, character())), character())
  expect_match(spec$annual_protection, "Native time.*no fixed annual term")
  expect_identical(.search_prepare_spec(model)$year, "year")
  expect_error(.search_prepare_spec(model, "fyear"), "matching retained native temporal")
  model$spatiotemporal <- "off"
  expect_error(.search_prepare_spec(model, "year"), "matching retained native temporal")
  model$time_varying <- ~depth
  expect_s3_class(.search_formula(.search_prepare_spec(model, "year"), character()), "formula")
  model$time_varying <- ~0
  expect_error(.search_prepare_spec(model, "year"), "matching retained native temporal")
  model$formula <- list(y ~depth, y ~depth)
  model$family$delta <- TRUE
  model$spatiotemporal <- c("off", "iid")
  expect_error(.search_prepare_spec(model, "year", component = "occurrence"), "matching retained native temporal")
  expect_match(.search_prepare_spec(model, "year", component = "positive")$annual_protection, "Native time")

  tiny <- search_term_model(y ~depth, "tinyVAST")
  tiny$internal$time_column <- "year"
  tiny$internal$spacetime_term_ram <- list(output = list(ram = matrix(1, nrow = 1)))
  spec <- .search_prepare_spec(tiny)
  expect_identical(spec$year, "year")
  expect_match(spec$annual_protection, "Native time")
  expect_true(.search_legal(spec, character()))
  tiny$internal$spacetime_term_ram$output$ram <- matrix(numeric(), nrow = 0L, ncol = 1L)
  expect_error(.search_prepare_spec(tiny, "year"), "matching retained native temporal")
  tiny$internal$time_term <- ~1
  expect_match(.search_prepare_spec(tiny)$annual_protection, "Native time")
  tiny$internal$time_column <- "fyear"
  expect_error(.search_prepare_spec(tiny, "year"), "matching retained native temporal")
  ordinary <- search_term_model(y ~depth)
  expect_error(.search_prepare_spec(ordinary, "year"), "annual predictor")
  dummy <- structure(list(formula = y ~year + depth, family = list(delta = FALSE),
    time = "constant_time", spatiotemporal = "off"), class = "sdmTMB")
  expect_identical(.search_prepare_spec(dummy)$year, "year")
  dummy <- search_term_model(y ~year + depth, "tinyVAST")
  dummy$internal$time_column <- "constant_time"
  expect_identical(.search_prepare_spec(dummy)$year, "year")
  dummy <- search_term_model(y ~season + fyear + depth)
  expect_identical(.search_prepare_spec(dummy)$year, "fyear")
})
