test_that("matched Poisson and NB2 checks reveal deliberately omitted overdispersion", {
  skip_if_not_installed("glmmTMB")
  skip_if_not_installed("DHARMa", "0.4.7")
  set.seed(20261013)
  d <- data.frame(year = factor(rep(2010:2014, each = 120)), x = rnorm(600))
  d$y <- rnbinom(600, mu = exp(1 + 0.4 * d$x), size = 0.8)
  poisson_fit <- glmmTMB::glmmTMB(y ~ year + x, data = d, family = poisson())
  nb_fit <- glmmTMB::glmmTMB(y ~ year + x, data = d, family = glmmTMB::nbinom2())
  rng <- .Random.seed
  checks <- lapply(list(poisson_fit, nb_fit), check_cpue,
    nsim = 100L, seed = 20261013L, conditioning = "fitted")
  disp <- lapply(checks, function(x) x$overall[x$overall$check == "dispersion", ])
  expect_gt(disp[[1]]$statistic, 1.5)
  expect_lt(disp[[1]]$p_value, 0.05)
  expect_identical(disp[[1]]$status, "review")
  expect_gt(disp[[2]]$statistic, 0.5)
  expect_lt(disp[[2]]$statistic, 1.5)
  expect_gt(disp[[2]]$p_value, 0.05)
  expect_identical(disp[[2]]$status, "no_flag")
  expect_identical(checks[[1]]$residuals$observations$observed, checks[[2]]$residuals$observations$observed)
  expect_identical(checks[[1]]$term_inventory, checks[[2]]$term_inventory)
  expect_identical(.Random.seed, rng)
  expect_match(disp[[1]]$method, "DHARMa nonparametric")
  expect_match(disp[[1]]$message, "not calibrated")
})
